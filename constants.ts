export const getTheme = (id: string, isDark: boolean): Theme => {
  const palette = PALETTES[id] || PALETTES.classic;
  const config = isDark ? palette.dark : palette.light;
  return {
    id: palette.id,
    dotColor: palette.dotColor,
    isDark,
    ...config,
  };
};

